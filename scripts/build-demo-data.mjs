/** Regenerate the immutable fixture module from the editable seed dataset. */
import { readFileSync, writeFileSync } from 'node:fs';
const data = JSON.parse(readFileSync(new URL('../demo/seed/dataset.json', import.meta.url), 'utf8'));
const moduleSource = `// Generated by scripts/build-demo-data.mjs.
const freeze = object => {
  if (object && typeof object === 'object') {
    Object.values(object).forEach(freeze);
    Object.freeze(object);
  }
  return object;
};
export default freeze(${JSON.stringify(data, null, 2)});
`;
writeFileSync(new URL('../src/graph/demoData.js', import.meta.url), moduleSource);
